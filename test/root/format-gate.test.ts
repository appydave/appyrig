import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import * as prettierApi from 'prettier';

/**
 * The format gate is `prettier --check .` in CI. Prettier's own behaviour is not tested here. What
 * this guards is the ignore file: a folder of app source added to .prettierignore leaves the gate
 * silently, and every check still passes.
 */

const ROOT = new URL('../..', import.meta.url).pathname;

describe('Feature: the format gate does not hide app source', () => {
  // The only things the format gate may skip. Adding a folder of app source to .prettierignore
  // removes it from the gate silently, so a new entry here is a decision, made in this file.
  const MAY_BE_IGNORED = [
    'test/fixtures/', // recorded captures, kept as recorded
    'test/root/fixtures/', // vendored OpenRig bytes (Apache-2.0)
    'server/src/core/vendor/', // vendored fli-core, upstream bytes
    'api/', // generated by npm run api:gen
    'package-lock.json',
    '.claude/', // agent skills and tooling
    '.openrig/',
    '.agents/',
    '.codex/',
    'CLAUDE.local.md',
    '.mcp.json',
  ];

  it('Scenario: given every tracked file, then prettier ignores only fixtures, vendored, generated and tooling files', async () => {
    const tracked = execFileSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' })
      .split('\n')
      .filter(Boolean);
    const ignored: string[] = [];
    for (const f of tracked) {
      const info = await prettierApi.getFileInfo(join(ROOT, f), {
        ignorePath: join(ROOT, '.prettierignore'),
      });
      if (info.ignored) ignored.push(f);
    }
    expect(ignored.length, 'the ignore file should ignore something').toBeGreaterThan(0);
    const hidden = ignored.filter((f) => !MAY_BE_IGNORED.some((p) => f === p || f.startsWith(p)));
    expect(hidden, 'files hidden from the format gate').toEqual([]);
  });
});
