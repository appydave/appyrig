import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { make } from './entry.mjs';
import { collectLoaded } from './configs.mjs';
import { collectFiles } from './files.mjs';

const TEST_FILES_LABEL = 'tests';

const readJson = (root, file) => JSON.parse(readFileSync(join(root, file), 'utf8'));

const isOff = (setting) =>
  (Array.isArray(setting) ? setting[0] : setting) === 'off' || setting === 0;

/** Paths ESLint skips entirely (a block that is only `ignores`). */
const eslintIgnores = (block) =>
  block.files
    ? []
    : (block.ignores ?? []).map((pattern) => make({ source: 'eslint', kind: 'ignore', pattern }));

/** Rules a block switches off, labelled by the files it covers. */
function eslintOffs(block) {
  const files = block.files ?? ['**'];
  const label = files.includes('**/test/**') ? TEST_FILES_LABEL : files.join(',');

  return Object.entries(block.rules ?? {})
    .filter(([, setting]) => isOff(setting))
    .map(([rule]) => make({ source: 'eslint', kind: `off ${rule}`, pattern: label }));
}

/** Rules switched off, and paths ignored, by the ESLint config as ESLint loads it. */
const fromEslint = (config) =>
  config.flatMap((block) => [...eslintIgnores(block), ...eslintOffs(block)]);

/** One knip workspace: its `ignore` entries and its negative `project` patterns. */
const knipWorkspace = ([name, space]) => [
  ...(space.ignore ?? []).map((pattern) =>
    make({ source: 'knip', where: name, kind: 'ignore', pattern })
  ),
  ...(space.project ?? [])
    .filter((p) => p.startsWith('!'))
    .map((pattern) => make({ source: 'knip', where: name, kind: 'project', pattern })),
];

const fromKnip = (root) =>
  Object.entries(readJson(root, 'knip.json').workspaces ?? {}).flatMap(knipWorkspace);

const fromJscpd = (root) =>
  (readJson(root, '.jscpd.json').ignore ?? []).map((pattern) =>
    make({ source: 'jscpd', kind: 'ignore', pattern })
  );

/** Every scoped-out path and switched-off rule in the sources this generator reads. */
export const collect = (root, configs) => [
  ...fromEslint(configs.eslint),
  ...fromKnip(root),
  ...fromJscpd(root),
  ...collectFiles(root),
  ...collectLoaded(root, configs),
];

/** Exemptions with no reason, and reasons whose exemption is gone. */
export function problems(entries, reasons) {
  const keys = new Set(entries.map((e) => e.key));
  const missing = entries.filter((e) => !(e.key in reasons)).map((e) => e.key);
  const stale = Object.keys(reasons).filter((k) => !keys.has(k));

  return { missing, stale };
}

const isUnknown = (reason) => reason.startsWith('reason unknown');
const cell = (text) => text.replaceAll('|', '\\|');

/** Reasons in order of first use, each with a short id the table rows point at. */
function numbered(entries, reasons) {
  const ids = new Map();

  for (const e of entries) {
    const reason = reasons[e.key] ?? 'NO REASON';

    if (!ids.has(reason)) {
      ids.set(reason, `R${ids.size + 1}`);
    }
  }

  return ids;
}

/** Exemption lists this document does not read yet: their absence here is not an absence of exemptions. */
const NOT_LISTED =
  'Not listed here: scripts/oxlint-gate.mjs NOT_SCANNED, lint/gates/archlint-scan.mjs ARCHLINT_EXCLUDES and SKIPPED_FILE, scripts/arch-strings.mjs SKIP, ALLOWED and COPY_ALLOWED, lint/root-imports-codemod.mjs NOT_SCANNED; also not listed: the inline disables in source (eslint-disable, v8 and istanbul ignore, oxlint-disable; 30 when counted on 2026-11-09) and the suppression baselines (eslint-suppressions.json, stylelint-suppressions.json, and the scores, oxlint, coupling and folder baselines).';

/** The text of docs/gates.md. */
export function render(entries, reasons) {
  const ids = numbered(entries, reasons);
  const sources = [...new Set(entries.map((e) => e.source))].join(', ');
  const rows = entries.map(
    (e) =>
      `| ${e.source} | ${cell(e.where || '-')} | ${cell(e.kind)} | \`${cell(e.pattern)}\` | ${ids.get(reasons[e.key] ?? 'NO REASON')} |`
  );
  const unknown = entries.filter((e) => isUnknown(reasons[e.key] ?? '')).length;

  return [
    '# Gate exemptions',
    '',
    `<!-- GENERATED by \`npm run docs:gates\` from the configs behind these sources: ${sources}. Do not edit by hand. -->`,
    '',
    'Generated: do not edit. Regenerate with `npm run docs:gates`; `test/root/docs/gates-doc.test.ts` fails when this file is stale.',
    'Reasons live in `scripts/gates-doc/reasons.mjs`. A reason starting "reason unknown" means nothing in the repo says why.',
    '',
    NOT_LISTED,
    '',
    `${entries.length} exemptions, ${unknown} with reason unknown.`,
    '',
    '| Source | Where | Kind | Path or rule | Reason |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Reasons',
    '',
    ...[...ids].map(([reason, id]) => `- **${id}**: ${cell(reason)}`),
    '',
  ].join('\n');
}
